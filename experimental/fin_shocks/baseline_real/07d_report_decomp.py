def share(fci, model, h, era, src, var, mode="infer"):
    g = S[(S["mode"] == mode) & (S.fci == fci) & (S.model == model) & (S.h == h) & (S.era == era) & (S.source == src)]; return float(g[var].iloc[0])
def band(fci, model, h, era, src, var, mode="infer"):
    g = B[(B["mode"] == mode) & (B.fci == fci) & (B.model == model) & (B.h == h) & (B.era == era) & (B.source == src) & (B["var"] == var)]
    return (float(g.p5.iloc[0]), float(g.p95.iloc[0])) if len(g) else (np.nan, np.nan)

