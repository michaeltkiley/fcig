"""Step 6. How noisy is a monthly proxy VAR if the estimated r*-gap model is the true process?  (lib/simulate.py describes the design)
   python3 06_proxy_simulation.py [--sims 1000]
1,000 samples of 369 months generated by the model (the data's calendar and announcement days); on each, the monthly proxy VAR with and without the FCI and the monthly window-impact estimator,
12 lags, as in step 4. Output: results/proxy_sim_rstar.csv (one row per sample) and results/proxy_sim_summary.csv (data estimate, true response, simulated median and 5th/95th percentiles)."""
import argparse
import numpy as np, pandas as pd
from lib import simulate as SM
from lib.paths import RESULTS

ap = argparse.ArgumentParser(); ap.add_argument("--sims", type=int, default=1000); a = ap.parse_args()
dg, df = SM.run(S=a.sims); df.round(5).to_csv(RESULTS / "proxy_sim_rstar.csv", index=False)
obs = {"nofci": pd.read_csv(RESULTS / "monthly_rstar_0_1996-01.csv"), "fci": pd.read_csv(RESULTS / "monthly_rstar_rstar_1996-01.csv")}
def dat(s_, ident, v, h, col="r"):
    d = obs[s_]; return float(d[(d.lags == 12) & (d.ident == ident) & (d["var"] == v) & (d.h == h)].iloc[0][col])
rows = []
def add(system, q, data, truth, sim):
    sim = np.asarray(sim, float); rows.append(dict(system=system, quantity=q, data=data, truth=truth, sim_median=float(np.median(sim)), sim_p05=float(np.percentile(sim, 5)), sim_p95=float(np.percentile(sim, 95)), share_le_data=float(np.mean(sim <= data))))
add("proxy_fci", "F", float(obs["fci"][obs["fci"].lags == 12].F.iloc[0]), np.nan, df["fci_F"])
add("proxy_fci", "u12", dat("fci", "P1", "u", 12), dg.truth[("u", 12)], df["fci_u12"]); add("proxy_fci", "P24", dat("fci", "P1", "P", 24), dg.truth[("P", 24)], df["fci_P24"])
add("proxy_nofci", "u12", dat("nofci", "P1", "u", 12), dg.truth[("u", 12)], df["nofci_u12"])
add("window", "u12", dat("fci", "WE", "u", 12), dg.truth_window[("u", 12)], df["we_u12"])
S = pd.DataFrame(rows); S.to_csv(RESULTS / "proxy_sim_summary.csv", index=False, float_format="%.4f"); print(S.round(2).to_string(index=False))
